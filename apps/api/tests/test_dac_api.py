def _first_supported(client: TestClient) -> dict:
    body = client.get("/api/v1/dac/catalog").json()
    for model in body["models"]:
        if model["supported"] and model["validated_shapes"]:
            return model
    raise AssertionError("no supported model with a validated shape in the catalog")


def test_estimate_endpoint_returns_a_full_breakdown(client: TestClient):
    model = _first_supported(client)
    response = client.post(
        "/api/v1/dac/estimate",
        json={
            "model_id": model["id"],
            "shape": model["validated_shapes"][0],
            "concurrency": 8,
            "prompt_tokens": 2000,
            "response_tokens": 200,
        },
    )
    assert response.status_code == 200
    body = response.json()
    assert body["vram"]["total_gb"] > 0
    assert body["performance"]["inference_speed_tps"] > 0
    assert body["confidence"]["tier"] in ("measured", "interpolated", "modeled")
    assert body["cost"]["unit_hours"] > 0
    assert body["oracle_validated"] is True


