# ── Recommender degradation ──────────────────────────────────────────────────


class ExplodingModel:
    """A provider that fails the way a stopped Ollama does."""

    name = "exploding"

    async def generate(self, request, on_token=None, *, model_aliases=None, on_reasoning=None):
        raise RuntimeError("model backend unreachable")


class ReorderingModel:
    """A provider that returns a valid reordering plus a bogus extra model."""

    name = "reordering"

    def __init__(self, order: list[str]) -> None:
        self._order = order
        self.seen_aliases: dict | None = None

    async def generate(self, request, on_token=None, *, model_aliases=None, on_reasoning=None):
        import json as _json

        from waqil_api.contracts import ModelResultV1

        self.seen_aliases = model_aliases
        payload = {
            "order": [*self._order, "hallucinated/model-that-does-not-exist"],
            "rationales": {self._order[0]: "Best fit for the stated task."},
            "summary": "Pick the first one.",
        }
        return ModelResultV1(model="fake-model", content=_json.dumps(payload))


@pytest.mark.anyio
async def test_recommendation_survives_a_dead_model_backend(catalog: DacCatalog):
    """A model outage must cost the prose, never the ranking.

    Sizing and cost are computed by the host and are exact; only the judgement
    of task fit depends on the model. Losing the whole answer because Ollama is
    stopped would make the tab useless in exactly the offline case Metis exists
    to serve.
    """
    service = DacService(catalog, model=ExplodingModel())
    result = await service.recommend(
        DacRecommendRequestV1(use_case="A coding assistant for Python services")
    )
    assert result.candidates
    assert result.model_backed is False
    assert any("without a model call" in note for note in result.notes)


@pytest.mark.anyio
async def test_model_may_reorder_but_never_introduce_a_model(catalog: DacCatalog):
    """The model reorders a host-validated list; anything it invents is dropped."""
    baseline = DacService(catalog).\
        _shortlist(DacRecommendRequestV1(use_case="A coding assistant for Python services"))
    assert len(baseline) > 1
    reversed_ids = [candidate.model_id for candidate in reversed(baseline)]

    provider = ReorderingModel(reversed_ids)
    service = DacService(catalog, model=provider)
    result = await service.recommend(
        DacRecommendRequestV1(use_case="A coding assistant for Python services")
    )
    returned = [candidate.model_id for candidate in result.candidates]
    assert returned == reversed_ids
    assert "hallucinated/model-that-does-not-exist" not in returned
    assert result.model_backed is True
    assert result.summary == "Pick the first one."
    assert result.candidates[0].rationale


@pytest.mark.anyio
async def test_model_can_promote_a_modern_model_beyond_the_visible_shortlist(
    catalog: DacCatalog,
):
    request = DacRecommendRequestV1(
        use_case=(
            "Two use cases: 1. Coding assistant "
            "2. Document/image extraction solution"
        ),
        limit=5,
    )
    provider = ReorderingModel(["Qwen/Qwen3.6-35B-A3B"])

    result = await DacService(catalog, model=provider).recommend(request)

    assert len(result.candidates) == request.limit
    assert result.candidates[0].model_id == "Qwen/Qwen3.6-35B-A3B"


@pytest.mark.anyio
async def test_recommender_uses_the_configured_model_preference(catalog: DacCatalog):
    """Whichever model the user pinned is the one that gets asked."""

    class Preference:
        def resolve_aliases(self) -> dict[str, str]:
            return {"planner": "my-pinned-model", "_provider": "local"}

    provider = ReorderingModel(["placeholder"])
    service = DacService(catalog, model=provider, preference=Preference())
    await service.recommend(DacRecommendRequestV1(use_case="A coding assistant"))
    assert provider.seen_aliases == {"planner": "my-pinned-model", "_provider": "local"}


def test_a_measured_configuration_reports_oracles_numbers_not_modeled_ones(
    client: TestClient,
):
    """When the badge says "measured", the metrics beside it must be measured.

    Oracle publishes gpt-oss-120b on OAI_H100_X2 at concurrency 32 for the Chat
    scenario. The roofline predicts ~13% higher there, and showing that under a
    "measured" label is the one case where the confidence badge would actively
    mislead rather than merely approximate.
    """
    response = client.post(
        "/api/v1/dac/estimate",
        json={
            "model_id": "openai/gpt-oss-120b",
            "shape": "OAI_H100_X2",
            "concurrency": 32,
            "prompt_tokens": 100,
            "response_tokens": 100,
        },
    )
    assert response.status_code == 200
    body = response.json()
    assert body["confidence"]["tier"] == "measured"
    published = body["published"]
    assert published is not None
    assert body["performance"]["inference_speed_tps"] == pytest.approx(
        published["inference_speed_tps"]
    )
    assert body["performance"]["ttft_s"] == pytest.approx(published["ttft_s"])
    assert any("published measurements" in note for note in body["notes"])


def test_scaling_a_measured_row_to_many_units_falls_back_to_the_model(
    client: TestClient,
):
    """Oracle benchmarks one unit; multiplying that up is modelling, not measuring."""
    response = client.post(
        "/api/v1/dac/estimate",
        json={
            "model_id": "openai/gpt-oss-120b",
            "shape": "OAI_H100_X2",
            "units": 4,
            "concurrency": 32,
            "prompt_tokens": 100,
            "response_tokens": 100,
        },
    )
    assert response.status_code == 200
    body = response.json()
    assert body["performance"]["inference_speed_tps"] != pytest.approx(
        body["published"]["inference_speed_tps"]
    )
    assert not any("published measurements" in note for note in body["notes"])


def test_benchmarked_shapes_stay_selectable_even_when_not_importable(
    client: TestClient, catalog: DacCatalog
):
    """The only measured configurations must remain reachable.

    Oracle's published grids run on an OpenAI-reserved shape that is not offered
    for model import. Exposing only importable shapes would hide the one tier
    backed by real measurements behind a modeled number.
    """
    body = client.get("/api/v1/dac/catalog").json()
    by_id = {model["id"]: model for model in body["models"]}
    gpt_oss = by_id["openai/gpt-oss-120b"]
    assert "OAI_H100_X2" in gpt_oss["benchmarked_shapes"]

    shapes = {shape["key"]: shape for shape in body["shapes"]}
    assert shapes["OAI_H100_X2"]["importable"] is False

    # And most models have no benchmarked shape at all, so the field is not
    # quietly duplicating the validated list.
    assert not by_id["Qwen/Qwen3-32B"]["benchmarked_shapes"]
