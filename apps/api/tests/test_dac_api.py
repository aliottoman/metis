"""End-to-end tests for the sizing endpoints and the vendored catalog.

The catalog-integrity tests matter more than they look: the catalog is
regenerated by hand from Oracle's docs and Hugging Face, so a silent scraper
regression — a renamed shape, a family page that stopped parsing, an
architecture field that vanished — would not break any code path. It would just
quietly shrink what the tab can answer. These assert the shape of the data, not
its contents, so they survive Oracle publishing new models.
"""
from __future__ import annotations

import pytest
from fastapi.testclient import TestClient

from waqil_api.dac_catalog import DacCatalog
from waqil_api.dac_service import DacService
from waqil_api.contracts import DacRecommendRequestV1


@pytest.fixture(scope="module")
def catalog() -> DacCatalog:
    return DacCatalog()


# ── Catalog integrity ────────────────────────────────────────────────────────


def test_catalog_loads_models_shapes_and_gpus(catalog: DacCatalog):
    assert len(catalog.models) > 50
    assert len(catalog.shapes) >= 24
    assert {"A10", "A100_40G", "A100_80G", "H100", "H200", "B200"} <= set(catalog.gpus)


def test_every_shape_resolves_to_a_known_gpu(catalog: DacCatalog):
    for shape in catalog.shapes.values():
        assert shape.gpu.key in catalog.gpus
        assert shape.gpu_count >= 1
        assert shape.ai_units > 0


def test_every_validated_shape_oracle_lists_actually_exists(catalog: DacCatalog):
    """A shape name Oracle publishes must resolve, directly or via an alias.

    Oracle spells the same shape both ways across pages (A100_80GB_X2 and
    A100_80G_X2). If an alias is dropped the model silently loses its only
    validated shape and drops out of every recommendation.
    """
    unresolved = [
        (record.id, name)
        for record in catalog.models.values()
        for name in record.validated_shapes
        if catalog.shape(name) is None
    ]
    assert not unresolved, f"unresolved validated shapes: {unresolved[:5]}"


def test_supported_models_carry_the_fields_the_kv_math_needs(catalog: DacCatalog):
    supported = [record for record in catalog.models.values() if record.architecture]
    assert len(supported) > 50
    for record in supported:
        architecture = record.architecture
        assert architecture is not None
        assert architecture.num_layers > 0
        assert architecture.hidden_size > 0
        assert architecture.num_key_value_heads > 0
        assert architecture.head_dim > 0
        assert architecture.attention_type in ("mha", "gqa", "mla")


def test_unsupported_models_say_why_rather_than_going_blank(catalog: DacCatalog):
    """A model Oracle validates but the roofline cannot describe still explains itself."""
    unsupported = [record for record in catalog.models.values() if not record.architecture]
    for record in unsupported:
        assert record.unsupported_reason, f"{record.id} has no explanation"
    # Image and audio models are the expected members of that set.
    assert any(
        record.capability not in ("TEXT_TO_TEXT", "IMAGE_TEXT_TO_TEXT")
        for record in unsupported
    )


def test_mixture_of_experts_models_record_their_expert_split(catalog: DacCatalog):
    moe = [
        record
        for record in catalog.models.values()
        if record.architecture and record.architecture.is_moe
    ]
    assert moe, "expected MoE models in the import catalog"
    for record in moe:
        architecture = record.architecture
        assert architecture is not None
        assert architecture.params_expert_total > 0
        assert 0 < architecture.params_expert_active <= architecture.params_expert_total


def test_calibration_joins_benchmarks_to_catalog_models(catalog: DacCatalog):
    """The benchmark join has to keep working, or calibration silently empties."""
    assert catalog.calibration_samples
    assert catalog.coefficients.fitted
    assert catalog.coefficients.decode_median_error is not None


def test_provenance_reports_dates_and_the_unverified_price(catalog: DacCatalog):
    provenance = catalog.provenance()
    assert provenance["models"]["generated_at"]
    assert provenance["benchmarks"]["generated_at"]
